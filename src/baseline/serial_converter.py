class SerialConverter:
    def convert(self, stim_circuit):
        """
        Stim回路を直列的なQCCD命令リスト（文字列）に変換する。
        """
        lines = []
        
        # QCCD DSLのヘッダーコメント
        lines.append("# Generated by SerialConverter (Naive Baseline)")
        lines.append("")

        for instruction in stim_circuit:
            name = instruction.name
            targets = instruction.targets_copy()
            
            # --- Gate Conversion ---
            if name == "H":
                # H -> 2 Rotations (例: Ry(pi/2) -> Rx(pi))
                # ※ あなたの環境で動作確認済みのパラメータに書き換えてください
                # 仮定: H = R(1.5708, 1.5708) -> R(3.1416, 3.1416) ?
                # ここでは、一般的に使われる H 分解の一例を入れています。
                # 既存の出力と合わせてください。
                for t in targets:
                    q = t.value
                    # H = Ry(pi/2) * Rx(pi) のような分解
                    lines.append(f"R {q} 1.5708 1.5708") # Angle 2
                    lines.append(f"R {q} 3.1416 0.0")   # Angle 1
            
            elif name == "CX" or name == "CNOT":
                # CNOT -> R_c -> MS -> R_c -> R_t -> R_c
                # Stimはターゲットペアを持つ: [c1, t1, c2, t2...]
                for i in range(0, len(targets), 2):
                    c = targets[i].value
                    t = targets[i+1].value
                    
                    # パラメータは実験環境のものに合わせて調整してください
                    lines.append(f"R {c} 1.5708 1.5708") # R_c
                    lines.append(f"MS {c} {t} 0.25")     # MS
                    lines.append(f"R {c} 1.5708 3.1416") # R_c
                    lines.append(f"R {t} 1.5708 3.1416") # R_t
                    lines.append(f"R {c} 1.5708 4.7124") # R_c

            elif name == "M" or name == "MEASURE":
                for t in targets:
                    lines.append(f"MEASURE {t.value}")

            elif name == "R" or name == "RESET":
                for t in targets:
                    lines.append(f"RESET {t.value}")
            
            # TICKなどは無視

        return lines