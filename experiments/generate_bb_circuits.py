"""Bivariate bicycle (BB) circuit generator.

2 つの既知の BB code (Bravyi et al. 2024, arXiv:2308.07915) を
`qldpc.codes.BBCode` (https://github.com/qiskit-community/qcode-discovery
で使われているのと同じライブラリ) で構成し、 circuits/bb_*.py を生成する。

Hx/Hz 抽出後の処理 (stabilizer list 化 / Stim 回路構築 / logical Z 計算 /
module 保存) は src/css_code_utils.py に委譲する (HGP と共通インフラ)。

**注意**: `qldpc` は numpy>=2.2 / stim dev-build を要求し、 メインの
requirements.txt や HGP 用の venv/ とも依存関係が異なるため、 専用の
`venv_bb/` (Python 3.10+) で実行すること:

  python3.10 -m venv venv_bb
  ./venv_bb/bin/pip install qldpc numpy matplotlib stim pymatching
  ./venv_bb/bin/python experiments/generate_bb_circuits.py

生成する 2 つの符号 (どちらも A=x^3+y+y^2, B=y^3+x+x^2 — Bravyi et al. の
"gross code" 系列。 同じ多項式で lattice サイズだけ変える):
  - bb_72_12_6:   (ell,m)=(6,6)  -> [[72,12,6]]   (最小の既知良好 BB code)
  - bb_144_12_12: (ell,m)=(12,6) -> [[144,12,12]] (= "gross code"、 本家)

distance は qldpc の MILP 計算 (分・時間単位) を走らせず、 Bravyi et al.
2024 で確立済みの値をそのまま使う (FOM=k*d^2/n で整合性確認済み: 72 code
12*36/72=6.0、 144 code 12*144/144=12.0)。
"""

import sys
from pathlib import Path

REPO = Path(__file__).parent.parent
sys.path.insert(0, str(REPO / 'src'))
sys.path.insert(0, str(REPO / 'circuits'))

import numpy as np
import sympy
from sympy.abc import x, y
from qldpc import codes as qldpc_codes

from css_code_utils import (
    css_stabilizers,
    build_css_stim_circuit,
    save_css_circuit_module,
    compute_logical_z_operators,
)
from qccd_parser import parse
from dag_builder import DAGBuilder
from qccd_compiler import QCCDArchitecture, QCCDCompiler, CompilerConfig


# (name, ell, m, d_known) — A, B は全例で共通 (Bravyi et al. gross code 系列)
A_TERMS_EXPR = x**3 + y + y**2
B_TERMS_EXPR = y**3 + x + x**2

BB_INSTANCES = [
    ('bb_72_12_6', 6, 6, 6),
    ('bb_144_12_12', 12, 6, 12),
]


def generate_one(name: str, ell: int, m: int, d_known: int, *,
                 run_compile_smoke_test: bool) -> dict:
    print(f"=== {name} ===")
    code = qldpc_codes.BBCode({x: ell, y: m}, A_TERMS_EXPR, B_TERMS_EXPR)
    n, k = code.num_qudits, code.dimension
    Hx = np.array(code.matrix_x, dtype=np.uint8)
    Hz = np.array(code.matrix_z, dtype=np.uint8)
    Q = n + 1
    print(f"  [[{n},{k},{d_known}]]  Q={Q}  (ell={ell}, m={m})")

    commute_violation = ((Hx @ Hz.T) % 2).any()
    print(f"  Hx@Hz^T == 0 (mod 2): {not commute_violation}")
    assert not commute_violation, "CSS commutation check failed"

    stabilizers = css_stabilizers(Hx, Hz)
    n_x = sum(1 for b, _ in stabilizers if b == 'X')
    n_z = sum(1 for b, _ in stabilizers if b == 'Z')
    weights = [len(s) for _, s in stabilizers]
    print(f"  stabilizers: {n_x} X-type, {n_z} Z-type "
          f"(weight min={min(weights)}, max={max(weights)})")

    logical_z_ops = compute_logical_z_operators(Hx, Hz)
    assert logical_z_ops.shape[0] == k, (
        f"found {logical_z_ops.shape[0]} logical Z ops, expected k={k}")
    logical_weights = logical_z_ops.sum(axis=1)
    print(f"  logical Z operators: {k} found "
          f"(weight min={logical_weights.min()}, max={logical_weights.max()})")

    data_qubits = list(range(n))
    ancilla_id = n
    stim_circuit = build_css_stim_circuit(stabilizers, ancilla_id)

    docstring = (
        f"{name}\n"
        f"Bivariate bicycle code (Bravyi et al. 2024, arXiv:2308.07915), "
        f"lattice (ell={ell}, m={m}), A=x^3+y+y^2, B=y^3+x+x^2.\n"
        f"[[{n},{k},{d_known}]] with 1 ancilla reuse (single-LIZ QCCD "
        f"convention). d={d_known} is the literature value (FOM=k*d^2/n "
        f"consistency-checked), not recomputed via MILP here.\n"
        f"LOGICAL_Z_OPERATORS[i] = data qubit support of the i-th logical Z "
        f"representative (ker(Hx) mod rowspan(Hz); not guaranteed minimum "
        f"weight).\n"
        f"Auto-generated by experiments/generate_bb_circuits.py."
    )
    out_path = REPO / 'circuits' / f'{name}.py'
    save_css_circuit_module(stim_circuit, data_qubits, [ancilla_id], out_path, docstring,
                            logical_z_operators=logical_z_ops, d_lower_bound=d_known,
                            d_is_exact=True)
    print(f"  saved: {out_path.relative_to(REPO)}")

    mod = __import__(name)
    program = parse(mod.CIRCUIT)
    dag = DAGBuilder(program, stabilizer_parallel=False).build()
    print(f"  parse+DAG OK: {len(program.instructions)} instructions")

    if run_compile_smoke_test:
        half = (len(mod.DATA_QUBITS) + 1) // 2
        mem_cap = max(20, half + len(mod.ANCILLA_QUBITS) + 4)
        arch = QCCDArchitecture.simple_mlm(liz_capacity=4, memory_capacity=mem_cap)
        initial = {}
        for i, qid in enumerate(mod.DATA_QUBITS):
            initial[qid] = 1 if i < half else 5
        for qid in mod.ANCILLA_QUBITS:
            initial[qid] = 5
        compiler = QCCDCompiler(arch, config=CompilerConfig())
        result = compiler.compile(dag, initial)
        print(f"  compile smoke test OK: {len(result.flat_ops)} ops, "
              f"{len(result.timesteps)} timesteps")

    return {'name': name, 'n': n, 'k': k, 'd': d_known, 'Q': Q}


def main():
    summary = []
    for name, ell, m, d_known in BB_INSTANCES:
        # bb_144_12_12 (145 qubits) は最大の既知比較対象 (d9 surface code: 82
        # qubits, hgp_hamming74: 59 qubits) の約 2 倍なので、 1 round compile
        # smoke test は小さい方 (bb_72_12_6) だけ実行する。 大きい方は notebook
        # 側でバックグラウンド実行して timing を確認する。
        smoke_test = (name == 'bb_72_12_6')
        summary.append(generate_one(name, ell, m, d_known, run_compile_smoke_test=smoke_test))

    print("\n=== Summary ===")
    for s in summary:
        print(f"  {s['name']}: [[{s['n']},{s['k']},{s['d']}]]  Q={s['Q']}")


if __name__ == '__main__':
    main()
