"""Code cycle time scaling: parallel/sequential time vs code distance.

Reads `par_time_ms` / `seq_time_ms` from `result.json` across d=3,5,7,9
for the snake_reuse1 family (single LIZ, 1 round). Plots two panels:

  1. canonical (greedy_alt placement) parallel + sequential times — matches
     the 2026-04-07 poster plot style
  2. placement comparison: greedy_alt vs split_even (archive) parallel time

This is a pure read-from-existing-JSON script — no compile required.
d=9 result.json is regenerated by `exp_phonon_scaling.py`, both placements
have been compiled previously.

Outputs:
    examples/cycle_time_scaling/plot.png
    examples/cycle_time_scaling/data.json
    examples/cycle_time_scaling/README.md
"""

import sys
import json
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / 'src'))

import matplotlib.pyplot as plt


REPO = Path(__file__).parent.parent
EXAMPLES = REPO / 'examples'

DISTANCES = [3, 5, 7, 9]

# Where to read data from. Each is a directory containing `d{N}_reuse1/result.json`.
SOURCES = {
    'greedy_alt (canonical)': EXAMPLES / 'single_liz',
    'split_even (archive)': EXAMPLES / '_archive' / '20260620_split_even' / 'single_liz',
}


def collect(source_dir: Path) -> list:
    rows = []
    for d in DISTANCES:
        rj = source_dir / f'd{d}_reuse1' / 'result.json'
        if not rj.exists():
            print(f"  [skip] {rj.relative_to(REPO)} not found")
            continue
        data = json.loads(rj.read_text(encoding='utf-8'))
        rows.append({
            'd': d,
            'par_time_ms': data.get('par_time_ms'),
            'seq_time_ms': data.get('seq_time_ms'),
            'compile_config': data.get('compile_config', {}),  # may be missing in archive
        })
    return rows


def main():
    print("Collecting cycle time data:")
    all_data = {}
    for label, src in SOURCES.items():
        rows = collect(src)
        all_data[label] = rows
        print(f"  {label}: {len(rows)} points")
        for r in rows:
            print(f"    d={r['d']}: par={r['par_time_ms']:>8.2f} ms, "
                  f"seq={r['seq_time_ms']:>8.2f} ms")

    outdir = EXAMPLES / 'cycle_time_scaling'
    outdir.mkdir(parents=True, exist_ok=True)

    # ---- Plot ----
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(11.5, 4.5))

    # Panel 1: canonical parallel + sequential
    canon = all_data.get('greedy_alt (canonical)', [])
    ds = [r['d'] for r in canon]
    par = [r['par_time_ms'] for r in canon]
    seq = [r['seq_time_ms'] for r in canon]
    ax1.plot(ds, par, 'o-', markersize=9, linewidth=2, color='C0', label='Parallel')
    ax1.plot(ds, seq, 's--', markersize=9, linewidth=2, color='gray', label='Sequential')
    for r in canon:
        ax1.annotate(f'{r["par_time_ms"]:.1f} ms',
                     (r['d'], r['par_time_ms']),
                     textcoords='offset points', xytext=(10, -3), fontsize=10)
    ax1.set_xlabel('Code distance $d$')
    ax1.set_ylabel('1-round cycle time (ms)')
    ax1.set_title('Cycle time vs code distance\n'
                  '(snake_reuse1, single LIZ, greedy_alt placement)')
    ax1.set_xticks(DISTANCES)
    ax1.grid(alpha=0.3)
    ax1.legend()

    # Panel 2: placement comparison (par_time only)
    archive = all_data.get('split_even (archive)', [])
    if archive:
        ax2.plot([r['d'] for r in canon], [r['par_time_ms'] for r in canon],
                 'o-', markersize=9, linewidth=2, color='C0',
                 label='greedy_alt (canonical)')
        ax2.plot([r['d'] for r in archive], [r['par_time_ms'] for r in archive],
                 'D--', markersize=9, linewidth=2, color='C3',
                 label='split_even (archive)')
        # Improvement ratio annotation
        for rc, ra in zip(canon, archive):
            if rc['d'] == ra['d'] and rc['par_time_ms'] and ra['par_time_ms']:
                ratio = ra['par_time_ms'] / rc['par_time_ms']
                ax2.annotate(f'×{ratio:.2f}',
                             (rc['d'], (rc['par_time_ms'] + ra['par_time_ms'])/2),
                             textcoords='offset points', xytext=(10, 0),
                             fontsize=9, color='C2')
    ax2.set_xlabel('Code distance $d$')
    ax2.set_ylabel('1-round parallel time (ms)')
    ax2.set_title('Placement strategy comparison\n'
                  '(×N annotation = split_even / greedy_alt ratio)')
    ax2.set_xticks(DISTANCES)
    ax2.grid(alpha=0.3)
    ax2.legend()

    fig.tight_layout()
    out_png = outdir / 'plot.png'
    fig.savefig(out_png, dpi=150)
    print(f"\n  saved plot: {out_png.relative_to(REPO)}")
    plt.close(fig)

    # ---- Simple plot (left panel only, simple title) ----
    fig_s, ax_s = plt.subplots(figsize=(6.5, 4.5))
    ax_s.plot(ds, par, 'o-', markersize=9, linewidth=2, color='C0', label='Parallel')
    ax_s.plot(ds, seq, 's--', markersize=9, linewidth=2, color='gray', label='Sequential')
    for r in canon:
        ax_s.annotate(f'{r["par_time_ms"]:.1f} ms',
                      (r['d'], r['par_time_ms']),
                      textcoords='offset points', xytext=(10, -3), fontsize=10)
    ax_s.set_xlabel('Code distance $d$')
    ax_s.set_ylabel('1-round cycle time (ms)')
    ax_s.set_title('Cycle time vs code distance')
    ax_s.set_xticks(DISTANCES)
    ax_s.grid(alpha=0.3)
    ax_s.legend()
    fig_s.tight_layout()
    out_simple = outdir / 'plot_simple.png'
    fig_s.savefig(out_simple, dpi=150)
    print(f"  saved plot: {out_simple.relative_to(REPO)}")
    plt.close(fig_s)

    # ---- data.json ----
    (outdir / 'data.json').write_text(
        json.dumps(all_data, indent=2, ensure_ascii=False) + "\n",
        encoding='utf-8')
    print(f"  saved data: {(outdir / 'data.json').relative_to(REPO)}")

    # ---- README ----
    rows_md = "\n".join(
        f"| {r['d']} | {r['par_time_ms']:.2f} | {r['seq_time_ms']:.2f} |"
        for r in canon
    )
    archive_section = ""
    if archive:
        rows_archive = "\n".join(
            f"| {r['d']} | {r['par_time_ms']:.2f} | {r['seq_time_ms']:.2f} |"
            for r in archive
        )
        archive_section = f"""

## Archived (split_even placement) for comparison

| d | par_time (ms) | seq_time (ms) |
|---|---------------|---------------|
{rows_archive}

`greedy_alt` で `par_time` が大きい d ほど比例的に改善する傾向。詳細は
`examples/_archive/20260620_split_even/README.md` 参照。
"""

    text = f"""# Code cycle time scaling vs distance

snake_reuse1 ファミリの 1 ラウンド実行時間 (parallel / sequential)
を符号距離 $d \\in \\{{3, 5, 7, 9\\}}$ について plot した。

## 設定 (canonical)

- placement strategy: **greedy_alt** (回路の登場順に LIZ 近接 zone から左右交互配置)
- eviction strategy: balanced
- architecture: simple_mlm (LIZ × 1, capacity 4; memory zones, capacity 20)
- ancilla: 1 個 (reuse される)
- rounds: 1 (single round of syndrome measurement)

## Canonical (greedy_alt) numbers

| d | par_time (ms) | seq_time (ms) |
|---|---------------|---------------|
{rows_md}
{archive_section}
## Notes

- これらの数字は 2026-04-07 のポスタープロット (`plots/code_cycle_scaling.png`)
  と一致するように、 placement strategy を当時と同じ `greedy_alt` に揃えた
  結果。 d=9 で par_time = 921 ms (poster: 919.2 ms) と誤差 0.2%。
- 過去 `split_even` で生成していた時代の数字も `examples/_archive/` から
  読めるので、 placement の効果を直接比較できる (右パネル)。
- 4/7 時点では `result.json` に `compile_config` が無かったため、 過去の
  数字との乖離の原因追跡が困難だった。 2026-06-21 以降の `result.json`
  には placement_strategy 等を `compile_config` セクションに必ず保存する。
"""
    (outdir / 'README.md').write_text(text, encoding='utf-8')
    print(f"\nDone. Output: {outdir.relative_to(REPO)}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
