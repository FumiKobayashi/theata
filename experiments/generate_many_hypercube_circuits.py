"""Many-hypercube code circuit generator.

Hayato Goto, "Many-hypercube codes: High-rate quantum error-correcting
codes for high-performance fault-tolerant quantum computing"
(arXiv:2403.16054). Many-hypercube (MHC) codes are the L-fold
concatenation of the [[6,4,2]] quantum error-detecting code.

`experiments/code_params/many_hypercube_l2_row_compact.json` already
contains the level-2 code's Hx, Hz, and (crucially) the logical_X/logical_Z
operators as dense 0/1 matrices -- no GF(2) construction needed here,
unlike HGP (hgp_check_matrices) or BB (qldpc.codes.BBCode). This script
just loads them and reuses the same css_code_utils.py pipeline
(css_stabilizers / build_css_stim_circuit / save_css_circuit_module) used
for HGP and BB.

Distance: d = d_1^level = 2^2 = 4. This is the standard concatenated-code
distance-multiplication property (minimum weight of a nontrivial logical
operator multiplies across concatenation levels, independent of decoder),
applied to the [[6,4,2]] (d_1=2) base code at level 2. Independently
confirmed here: every row of the provided logical_Z matrix has weight
exactly 4 (see verification print in main()).

Usage (runs in the main environment -- only needs numpy + the `ldpc`
already installed for BP+OSD; no qldpc/venv required, unlike BB):

    python experiments/generate_many_hypercube_circuits.py
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).parent.parent
sys.path.insert(0, str(REPO / 'src'))
sys.path.insert(0, str(REPO / 'circuits'))

import numpy as np

from css_code_utils import (
    css_stabilizers,
    build_css_stim_circuit,
    save_css_circuit_module,
)
from qccd_parser import parse
from dag_builder import DAGBuilder
from qccd_compiler import QCCDArchitecture, QCCDCompiler, CompilerConfig


JSON_PATH = REPO / 'experiments' / 'code_params' / 'many_hypercube_l2_row_compact.json'
NAME = 'many_hypercube_l2'
D_KNOWN = 4  # d_1^level = 2^2 (see module docstring)


def main():
    print(f"=== {NAME} ===")
    data = json.loads(JSON_PATH.read_text(encoding='utf-8'))
    meta = data['metadata']
    n = meta['n_physical']
    k = meta['k_logical']
    print(f"  source: {JSON_PATH.relative_to(REPO)}")
    print(f"  base_code={meta['base_code']}  level={meta['level']}")

    Hx = np.array(data['matrices']['Hx'], dtype=np.uint8)
    Hz = np.array(data['matrices']['Hz'], dtype=np.uint8)
    logical_Z = np.array(data['matrices']['logical_Z'], dtype=np.uint8)
    assert Hx.shape == (10, n) and Hz.shape == (10, n)
    assert logical_Z.shape[0] == k

    print(f"  [[{n},{k},{D_KNOWN}]]  Q={n + 1}")

    commute_violation = ((Hx @ Hz.T) % 2).any()
    print(f"  Hx@Hz^T == 0 (mod 2): {not commute_violation}")
    assert not commute_violation, "CSS commutation check failed"

    logical_commute_violation = ((Hx @ logical_Z.T) % 2).any()
    print(f"  Hx@logical_Z^T == 0 (mod 2): {not logical_commute_violation}")
    assert not logical_commute_violation, "logical_Z does not commute with Hx"

    logical_weights = logical_Z.sum(axis=1)
    print(f"  logical_Z weights: {sorted(set(logical_weights.tolist()))} "
          f"(all == {D_KNOWN} -> consistent with d={D_KNOWN})")
    assert (logical_weights == D_KNOWN).all(), (
        f"expected all logical_Z weights == {D_KNOWN}, got {set(logical_weights.tolist())}")

    stabilizers = css_stabilizers(Hx, Hz)
    n_x = sum(1 for b, _ in stabilizers if b == 'X')
    n_z = sum(1 for b, _ in stabilizers if b == 'Z')
    weights = [len(s) for _, s in stabilizers]
    print(f"  stabilizers: {n_x} X-type, {n_z} Z-type "
          f"(weight min={min(weights)}, max={max(weights)})")

    data_qubits = list(range(n))
    ancilla_id = n
    stim_circuit = build_css_stim_circuit(stabilizers, ancilla_id)

    docstring = (
        f"{NAME}\n"
        f"Many-hypercube code (Hayato Goto, arXiv:2403.16054): level-{meta['level']} "
        f"concatenation of the {meta['base_code']} quantum error-detecting code.\n"
        f"[[{n},{k},{D_KNOWN}]] with 1 ancilla reuse (single-LIZ QCCD convention). "
        f"d={D_KNOWN} = d_1^level = 2^2 (concatenated-code distance multiplication; "
        f"independently confirmed by all {k} logical_Z rows having weight exactly "
        f"{D_KNOWN} in the source data).\n"
        f"Hx/Hz/logical_Z sourced directly from "
        f"experiments/code_params/many_hypercube_l2_row_compact.json (column order: "
        f"{meta['column_order']}).\n"
        f"LOGICAL_Z_OPERATORS[i] = data qubit support of the i-th logical Z operator "
        f"(as provided by the source data, not recomputed).\n"
        f"Auto-generated by experiments/generate_many_hypercube_circuits.py."
    )
    out_path = REPO / 'circuits' / f'{NAME}.py'
    save_css_circuit_module(stim_circuit, data_qubits, [ancilla_id], out_path, docstring,
                            logical_z_operators=logical_Z, d_lower_bound=D_KNOWN,
                            d_is_exact=True)
    print(f"  saved: {out_path.relative_to(REPO)}")

    mod = __import__(NAME)
    program = parse(mod.CIRCUIT)
    dag = DAGBuilder(program, stabilizer_parallel=False).build()
    print(f"  parse+DAG OK: {len(program.instructions)} instructions")

    half = (len(mod.DATA_QUBITS) + 1) // 2
    mem_cap = max(20, half + len(mod.ANCILLA_QUBITS) + 4)
    arch = QCCDArchitecture.simple_mlm(liz_capacity=4, memory_capacity=mem_cap)
    initial = {}
    for i, qid in enumerate(mod.DATA_QUBITS):
        initial[qid] = 1 if i < half else 5
    for qid in mod.ANCILLA_QUBITS:
        initial[qid] = 5
    compiler = QCCDCompiler(arch, config=CompilerConfig())
    result = compiler.compile(dag, initial)
    print(f"  compile smoke test OK: {len(result.flat_ops)} ops, "
          f"{len(result.timesteps)} timesteps")

    print(f"\n=== Summary ===\n  {NAME}: [[{n},{k},{D_KNOWN}]]  Q={n + 1}")


if __name__ == '__main__':
    main()
