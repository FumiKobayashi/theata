"""Hypergraph product (HGP) circuit generator.

2つの小さい古典符号 (repetition / Hamming(7,4)) から HGP 量子符号を構成し、
circuits/hgp_rep3.py, circuits/hgp_hamming74.py を生成する。

構成は src/css_code_utils.py (hgp_check_matrices, css_code_params,
css_stabilizers, build_css_stim_circuit, save_css_circuit_module) に委譲。
GF(2) rank / 古典符号の exact distance は `ldpc` パッケージ
(https://github.com/quantumgizmos/ldpc) に委譲している。

**注意**: `ldpc` は numpy>=1.24 を要求するため、 メインの requirements.txt
とは別の隔離 venv が必要 (`requirements-ldpc.txt` 参照)。

  ./venv/bin/python experiments/generate_hgp_circuits.py

生成する 2 つの符号:
  - hgp_rep3:      H1=H2=repetition(3) -> [[13,1,3]]
                   (HGP(repetition, repetition) = 通常の surface code に
                   帰着することが知られている、構成の正しさ確認用の最小例)
  - hgp_hamming74: H1=H2=Hamming(7,4) -> [[58,16,>=3]]
                   (genuinely LDPC な最初の例)

両方とも forward circuit を multi-round でそのまま再利用する (reverse 不要;
`recompile_multi_round` は (basis, frozenset(data_qubits)) の identity で
detector を作るため、 stabilizer の順序に依存しない)。
"""

import sys
from pathlib import Path

REPO = Path(__file__).parent.parent
sys.path.insert(0, str(REPO / 'src'))
sys.path.insert(0, str(REPO / 'circuits'))

import numpy as np
import ldpc.codes as codes

from css_code_utils import (
    hgp_check_matrices,
    css_code_params,
    css_stabilizers,
    build_css_stim_circuit,
    save_css_circuit_module,
    compute_logical_z_operators,
)
from qccd_parser import parse
from dag_builder import DAGBuilder
from qccd_compiler import QCCDArchitecture, QCCDCompiler, CompilerConfig


def generate_one(name: str, H_classical, *, run_compile_smoke_test: bool) -> dict:
    """H_classical を H1=H2 として HGP 符号を構成し circuits/<name>.py を保存。
    parse + DAG build は常に確認、 QCCDCompiler.compile() の 1 round smoke
    test は `run_compile_smoke_test=True` のときだけ実行する (大きい符号は
    重いのでデフォルトでは notebook 側のバックグラウンド実行に委ねる)。
    """
    print(f"=== {name} ===")
    params = css_code_params(H_classical, H_classical)
    n, k, Q, d_lb = params['n'], params['k'], params['Q'], params['d_lower_bound']
    print(f"  [[{n},{k},>={d_lb}]]  Q={Q}")

    Hx, Hz = params['Hx'], params['Hz']
    commute_violation = ((Hx @ Hz.T) % 2).any()
    print(f"  Hx@Hz^T == 0 (mod 2): {not commute_violation}")
    assert not commute_violation, "CSS commutation check failed"

    stabilizers = css_stabilizers(Hx, Hz)
    n_x = sum(1 for b, _ in stabilizers if b == 'X')
    n_z = sum(1 for b, _ in stabilizers if b == 'Z')
    weights = [len(s) for _, s in stabilizers]
    print(f"  stabilizers: {n_x} X-type, {n_z} Z-type "
          f"(weight min={min(weights)}, max={max(weights)})")

    logical_z_ops = compute_logical_z_operators(Hx, Hz)
    assert logical_z_ops.shape[0] == k, (
        f"found {logical_z_ops.shape[0]} logical Z ops, expected k={k}")
    logical_weights = logical_z_ops.sum(axis=1)
    print(f"  logical Z operators: {k} found "
          f"(weight min={logical_weights.min()}, max={logical_weights.max()})")

    data_qubits = list(range(n))
    ancilla_id = n
    stim_circuit = build_css_stim_circuit(stabilizers, ancilla_id)

    docstring = (
        f"{name}\n"
        f"Hypergraph product of two copies of the same classical code "
        f"(H1=H2, shape {H_classical.shape}).\n"
        f"[[{n},{k},>={d_lb}]] with 1 ancilla reuse (single-LIZ QCCD "
        f"convention).\n"
        f"LOGICAL_Z_OPERATORS[i] = data qubit support of the i-th logical Z "
        f"representative (ker(Hx) mod rowspan(Hz); not guaranteed minimum "
        f"weight).\n"
        f"Auto-generated by experiments/generate_hgp_circuits.py."
    )
    out_path = REPO / 'circuits' / f'{name}.py'
    save_css_circuit_module(stim_circuit, data_qubits, [ancilla_id], out_path, docstring,
                            logical_z_operators=logical_z_ops, d_lower_bound=d_lb)
    print(f"  saved: {out_path.relative_to(REPO)}")

    # Smoke test: parse + DAG build (cheap, always run)
    mod_name = name
    mod = __import__(mod_name)
    program = parse(mod.CIRCUIT)
    dag = DAGBuilder(program, stabilizer_parallel=False).build()
    print(f"  parse+DAG OK: {len(program.instructions)} instructions")

    if run_compile_smoke_test:
        half = (len(mod.DATA_QUBITS) + 1) // 2
        mem_cap = max(20, half + len(mod.ANCILLA_QUBITS) + 4)
        arch = QCCDArchitecture.simple_mlm(liz_capacity=4, memory_capacity=mem_cap)
        initial = {}
        for i, qid in enumerate(mod.DATA_QUBITS):
            initial[qid] = 1 if i < half else 5
        for qid in mod.ANCILLA_QUBITS:
            initial[qid] = 5
        compiler = QCCDCompiler(arch, config=CompilerConfig())
        result = compiler.compile(dag, initial)
        print(f"  compile smoke test OK: {len(result.flat_ops)} ops, "
              f"{len(result.timesteps)} timesteps")

    return {'name': name, 'n': n, 'k': k, 'Q': Q, 'd_lower_bound': d_lb}


def main():
    H_rep3 = codes.rep_code(3).toarray()
    H_hamming74 = codes.hamming_code(3).toarray()

    summary = []
    summary.append(generate_one('hgp_rep3', H_rep3, run_compile_smoke_test=True))
    summary.append(generate_one('hgp_hamming74', H_hamming74, run_compile_smoke_test=False))

    print("\n=== Summary ===")
    for s in summary:
        print(f"  {s['name']}: [[{s['n']},{s['k']},>={s['d_lower_bound']}]]  Q={s['Q']}")


if __name__ == '__main__':
    main()
