"""Phonon scaling plot: max transversal phonon vs code distance d.

Reads `examples/single_liz/d{3,5,7,9}_reuse1/result.json` and plots the
max transversal phonon (n_bar at the noisiest MS gate per round) as a
function of code distance d for the snake_reuse1 family (1-LIZ compiler).

For d=3/5/7, the result.json files already exist (regenerated by
`exp_build_examples.py`). For d=9 they don't, so this script compiles d=9
once and saves the canonical compile artifacts (flat_ops.txt /
timesteps.txt / result.json) via `formatter.save_compile_artifacts`. Noise
injection is intentionally skipped for d=9 — the lookup table tops out at
n_bar=20 and d=9 produces many MS gates exceeding it.

Usage:
    python experiments/exp_phonon_scaling.py
    python experiments/exp_phonon_scaling.py --recompile-d9   # force redo

Outputs:
    examples/phonon_scaling/plot.png
    examples/phonon_scaling/data.json
    examples/phonon_scaling/README.md
"""

import sys
import argparse
import json
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / 'src'))
sys.path.insert(0, str(Path(__file__).parent.parent / 'circuits'))

import matplotlib.pyplot as plt

from qccd_parser import parse
from dag_builder import DAGBuilder
from qccd_compiler import QCCDArchitecture, QCCDCompiler, CompilerConfig
from formatter import save_compile_artifacts
sys.path.insert(0, str(Path(__file__).parent.parent / 'experiments'))
from exp_multi_round import placement_greedy_alt

PLACEMENT_STRATEGY = "greedy_alt"


REPO = Path(__file__).parent.parent
EXAMPLES = REPO / 'examples'

# d → snake_reuse1 系の circuit module 名
CIRCUITS = {
    3: 'snake_reuse1',
    5: 'd5_reuse1',
    7: 'd7_reuse1',
    9: 'd9_reuse1',
}


# ==========================================
# d=9 compile (1 度だけ実行、 result.json を保存)
# ==========================================

def compile_d9(force: bool = False) -> Path:
    """d=9 を compile して examples/single_liz/d9_reuse1/ に compile artifacts を保存。

    既に result.json があり force=False なら再実行しない。
    Noise injection は走らせない (フォノン数取得には不要)。
    """
    outdir = EXAMPLES / 'single_liz' / 'd9_reuse1'
    result_json = outdir / 'result.json'
    if result_json.exists() and not force:
        print(f"[d=9] result.json already exists at {result_json.relative_to(REPO)}")
        return outdir

    mod_name = CIRCUITS[9]
    print(f"[d=9] compiling {mod_name} (this may take 1-3 min)...")
    mod = __import__(mod_name)

    half = (len(mod.DATA_QUBITS) + 1) // 2
    mem_cap = max(20, half + len(mod.ANCILLA_QUBITS) + 4)
    arch = QCCDArchitecture.simple_mlm(liz_capacity=4, memory_capacity=mem_cap)

    # greedy_alt: 回路の登場順に LIZ 近接 zone から左右交互配置 (canonical)
    initial = placement_greedy_alt(mod.DATA_QUBITS, mod.ANCILLA_QUBITS, mod)

    program = parse(mod.CIRCUIT)
    dag = DAGBuilder(program, stabilizer_parallel=False).build()
    compiler = QCCDCompiler(arch, config=CompilerConfig())
    result = compiler.compile(dag, initial)

    outdir.mkdir(parents=True, exist_ok=True)
    save_compile_artifacts(
        result, str(outdir),
        placement_strategy=PLACEMENT_STRATEGY,
        stabilizer_parallel=False,
        initial_placement=initial, arch=arch,
        circuit_name=mod_name, label='d9_reuse1',
    )
    print(f"[d=9] saved compile artifacts to {outdir.relative_to(REPO)}")
    return outdir


# ==========================================
# Phonon data collection
# ==========================================

def collect_phonon_data() -> list:
    """各 d の result.json から max phonon と cycle time を抽出する。"""
    data = []
    for d, mod_name in sorted(CIRCUITS.items()):
        result_json = EXAMPLES / 'single_liz' / f'd{d}_reuse1' / 'result.json'
        if not result_json.exists():
            print(f"  [skip] d={d}: {result_json.relative_to(REPO)} not found")
            continue
        with open(result_json, encoding='utf-8') as f:
            r = json.load(f)
        ph = r.get('phonon', {})
        data.append({
            'd': d,
            'n_data_qubits': d * d,
            'circuit': mod_name,
            'max_axial': ph.get('max_axial'),
            'max_transversal': ph.get('max_transversal'),
            'par_time_ms': r.get('par_time_ms'),
            'seq_time_ms': r.get('seq_time_ms'),
        })
    return data


# ==========================================
# Plot
# ==========================================

def plot_phonon(data: list, out_png: Path) -> None:
    ds = [r['d'] for r in data]
    trs = [r['max_transversal'] for r in data]

    fig, ax = plt.subplots(figsize=(6.5, 4.5))
    ax.plot(ds, trs, 'o-', markersize=10, linewidth=2, color='C0',
            label='Max transversal phonon')
    # lookup table 上限のリファレンスライン
    ax.axhline(20.0, color='red', linestyle='--', alpha=0.5,
               label='Lookup table max (n_bar=20)')
    # データラベル
    for r in data:
        ax.annotate(f'{r["max_transversal"]:.2f}',
                    (r['d'], r['max_transversal']),
                    textcoords='offset points', xytext=(8, 5),
                    fontsize=10)
    ax.set_xlabel('Code distance $d$')
    ax.set_ylabel(r'Max transversal phonon $\bar{n}_\perp$ (per round)')
    ax.set_title('Max transversal phonon vs code distance\n'
                 '(rotated surface code, snake_reuse1, single LIZ)')
    ax.set_xticks(ds)
    ax.grid(alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(out_png, dpi=150)
    print(f"  saved plot: {out_png.relative_to(REPO)}")
    plt.close(fig)


def write_readme(data: list, outdir: Path) -> None:
    rows = "\n".join(
        f"| {r['d']} | {r['n_data_qubits']} | {r['max_transversal']:.3f} | "
        f"{r['max_axial']:.2f} | {r['par_time_ms']:.2f} |"
        for r in data
    )
    text = f"""# Phonon scaling vs code distance

Maximum transversal (and axial) phonon count at MS gate execution time,
plotted as a function of code distance d for the snake_reuse1 family
(single LIZ compiler).

## Data (from `examples/single_liz/dX_reuse1/result.json`)

| d | n_data | max_transversal | max_axial | par_time_ms |
|---|--------|-----------------|-----------|-------------|
{rows}

## Files
- `plot.png` — max transversal phonon vs d (linear scale, with lookup
  table max reference at n_bar = 20)
- `data.json` — full per-d numbers (axial, transversal, par/seq time)

## Notes
- The Pauli-twirled error probability lookup table
  (`src/pauli_twirled_error_probabilities.csv`) is sampled at n_bar ∈
  {{0.01, 0.25, ..., 20.0}}. For larger phonons (d ≥ 5 already has 1 MS
  exceeding 20, d ≥ 7 has many) the value is clipped to 20 with a
  runtime warning.
- Per-round wall time (`par_time_ms`) is included for reference but not
  plotted here; see `examples/distance_scan/` (noisy simulation) for the
  end-to-end logical error rate behavior.
- d=9 is included here even though it exceeds the lookup table — the
  phonon track itself is independent of the lookup table, so the data is
  trustworthy. Noise simulation for d=9 is intentionally not produced.
"""
    (outdir / 'README.md').write_text(text, encoding='utf-8')


# ==========================================
# Main
# ==========================================

def main():
    parser = argparse.ArgumentParser(description='Phonon scaling plot')
    parser.add_argument('--recompile-d9', action='store_true',
                        help='Force recompile d=9 even if result.json exists')
    args = parser.parse_args()

    print("Ensuring d=9 compile artifacts exist...")
    compile_d9(force=args.recompile_d9)

    print("\nCollecting phonon data from existing result.json files:")
    data = collect_phonon_data()
    for r in data:
        print(f"  d={r['d']:>1d} (n_data={r['n_data_qubits']:>3d}): "
              f"max_tr={r['max_transversal']:>8.3f}, "
              f"max_ax={r['max_axial']:>10.2f}, "
              f"par={r['par_time_ms']:>8.2f} ms")

    outdir = EXAMPLES / 'phonon_scaling'
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / 'data.json').write_text(
        json.dumps(data, indent=2, ensure_ascii=False) + "\n",
        encoding='utf-8')
    print(f"\n  saved data: {(outdir / 'data.json').relative_to(REPO)}")

    plot_phonon(data, outdir / 'plot.png')
    write_readme(data, outdir)
    print(f"\nDone. Output: {outdir.relative_to(REPO)}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
